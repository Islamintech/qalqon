#!/bin/sh
# Regenerate deploy/cloudflare-real-ip.conf from Cloudflare's published ranges.
#
# Run as root on the server, then reload nginx. Writes to a temp file first so
# a failed download cannot leave a truncated config that breaks the site.
set -eu

OUT="${1:-/etc/nginx/conf.d/cloudflare-real-ip.conf}"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

{
    echo "# Generated by refresh-cloudflare-ips.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
    echo "# Source: https://www.cloudflare.com/ips/ — do not hand-edit."
    echo
    for url in https://www.cloudflare.com/ips-v4 https://www.cloudflare.com/ips-v6; do
        curl -fsS "$url" | while read -r cidr; do
            [ -n "$cidr" ] && echo "set_real_ip_from $cidr;"
        done
    done
    echo
    echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"

# A range list this short means the download returned junk; refuse to install it.
if [ "$(grep -c set_real_ip_from "$TMP")" -lt 10 ]; then
    echo "refusing to install: only $(grep -c set_real_ip_from "$TMP") ranges parsed" >&2
    exit 1
fi

cp "$TMP" "$OUT"
echo "wrote $OUT"
echo "now run: nginx -t && systemctl reload nginx"
